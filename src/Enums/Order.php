<?php

namespace MaxiStyle\EtrnBuilder\Enums;

/**
 * Справочники значений формата ФНС «электронный заказ (заявка) на перевозку»
 * (приказ ФНС России от 13.02.2023 № ЕД-7-26/108@, версия формата 5.01).
 *
 * Используются билдерами {@see \MaxiStyle\EtrnBuilder\Builders\OrderT1Builder}
 * и {@see \MaxiStyle\EtrnBuilder\Builders\OrderT2Builder} и рекомендованы к использованию
 * при заполнении сущностей `OrderT1`, `OrderT2`, `RoutePoint`, `OrderCargo`, `OrderSignatory`,
 * `Payment`, `Vehicle`.
 */
final class Order
{
    // -----------------------------------------------------------------
    // Функция документа (Документ@Функция) — OrderT1
    // -----------------------------------------------------------------

    /** Разовая перевозка без договора об организации перевозок. */
    public const string FUNCTION_ORDER = 'Заказ';

    /** Перевозка при наличии договора об организации перевозок (ДогОргПрвз обязателен). */
    public const string FUNCTION_REQUEST = 'Заявка';

    // -----------------------------------------------------------------
    // Операция в пункте маршрута (АдрПункт@Опер) — OrderT1
    // -----------------------------------------------------------------

    public const string OPERATION_LOADING = 'Погрузка';
    public const string OPERATION_UNLOADING = 'Выгрузка';

    // -----------------------------------------------------------------
    // Метод определения массы груза (ОпГруз@МетОпрМасс) — OrderT1
    // -----------------------------------------------------------------

    /** Взвешивание по общей массе. */
    public const string WEIGHT_METHOD_TOTAL = '01';

    /** Взвешивание поосно. */
    public const string WEIGHT_METHOD_AXLE = '02';

    /** Расчетная масса груза. */
    public const string WEIGHT_METHOD_CALCULATED = '03';

    // -----------------------------------------------------------------
    // Решение перевозчика (СодИнфПрв@СодОпер) — OrderT2
    // -----------------------------------------------------------------

    /** Заказ (заявка) принят перевозчиком. */
    public const string DECISION_ACCEPTED = '1';

    /** Заказ (заявка) отклонён — ПричОтк обязателен. */
    public const string DECISION_REJECTED = '2';

    // -----------------------------------------------------------------
    // Тип владения ТС (ТС@ТипВлад / Прицеп@ТипВлад) — Vehicle::$ownershipType
    // Хранится как int в сущности; при аренде/лизинге/безвозмездном использовании
    // обязателен блок ОснАрЛиз (rentLeaseDocument).
    // -----------------------------------------------------------------

    public const int OWNERSHIP_OWN = 1;             // собственность
    public const int OWNERSHIP_JOINT = 2;           // совместная собственность супругов
    public const int OWNERSHIP_RENT = 3;            // аренда
    public const int OWNERSHIP_LEASING = 4;         // лизинг
    public const int OWNERSHIP_FREE = 5;            // безвозмездное пользование

    // -----------------------------------------------------------------
    // Способ подтверждения полномочий подписанта (ПодпИнф*@СпосПодтПолном)
    //
    // Значения по формату ФНС (приказ ЕД-7-26/108@):
    //   1 — без доверенности (руководитель организации / ИП);
    //   2 — на основании доверенности, выданной в электронной форме и подписанной
    //       усиленной квалифицированной ЭП руководителя;
    //   3 — на основании машиночитаемой доверенности (МЧД, СвДоверЭл);
    //   4 — уполномоченное грузоотправителем лицо (иной документ);
    //   5 — на основании доверенности, оформленной на бумажном носителе (СвДоверБум);
    //   6 — иной способ, установленный законодательством.
    // -----------------------------------------------------------------

    public const string AUTHORITY_1 = '1';
    public const string AUTHORITY_2 = '2';
    public const string AUTHORITY_3 = '3';
    public const string AUTHORITY_4 = '4';
    public const string AUTHORITY_5 = '5';
    public const string AUTHORITY_6 = '6';

    // -----------------------------------------------------------------
    // Ставка НДС (РазмПлатРасчет@НалСт) — OrderT2
    // -----------------------------------------------------------------

    public const string VAT_0 = '0%';
    public const string VAT_10 = '10%';
    public const string VAT_20 = '20%';
    public const string VAT_10_110 = '10/110';
    public const string VAT_20_120 = '20/120';
    public const string VAT_NONE = 'без НДС';
    public const string VAT_AGENT = 'исчисляется агентом';
}